import socket
 
client = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
client.settimeout(3)
try:
    data, addr = client.recvfrom(1024)
    print("Ответ:", data.decode("utf-8"))
except socket.timeout:
    print("Ответа нет: сервер не запущен или пакет потерян")
client.close()

# UDP-клиент не получает ошибку сразу, потому что для UDP «отправить» означает «вытолкнуть пакет в сеть». 
# Всё, что происходит с пакетом дальше (потеря, недоставка, ICMP-ошибка), — это уже забота сети и приложения. 
# TCP же несёт ответственность за доставку и целостность соединения, поэтому он может сообщить об ошибке немедленно, если соединение разорвано.
